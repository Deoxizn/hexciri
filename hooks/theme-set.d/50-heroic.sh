# Point Heroic at the folder and select the generated theme.
#
# Two files are involved in Heroic 2.2x:
#   config.json        → defaultSettings.customThemesPath (main process scans it)
#   store/config.json  → top-level `theme` (renderer configStore; filename = id)
# A path already chosen by the user is preserved (the CSS is installed into
# that folder instead); only an empty/missing path is replaced with hexciri's
# own folder. Both writes are atomic — the launcher persists whole objects, so
# a half-written file would reset settings at next start.
if command -v python3 >/dev/null 2>&1; then
    if ! python3 - "$heroic_config" "$heroic_themes" "$theme_id" "$theme_file" <<'PYEOF'
import json
import os
import stat
import sys
import tempfile

config_path, default_dir, theme_id, theme_file = sys.argv[1:5]
config_dir = os.path.dirname(config_path) or "."
store_path = os.path.join(config_dir, "store", "config.json")


def load_json(path):
    if not os.path.isfile(path):
        return {}
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"hexciri heroic: keeping config untouched ({exc})", file=sys.stderr)
        return None
    return data if isinstance(data, dict) else {}


def write_json(path, data, indent):
    parent = os.path.dirname(path) or "."
    os.makedirs(parent, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(prefix=".config.", suffix=".json", dir=parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=indent, ensure_ascii=False)
            fh.write("\n")
        if os.path.isfile(path):
            os.chmod(tmp_path, stat.S_IMODE(os.stat(path).st_mode))
        os.replace(tmp_path, path)
    finally:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)


data = load_json(config_path)
store = load_json(store_path)
if data is None or store is None:
    sys.exit(3)

settings = data.get("defaultSettings")
if not isinstance(settings, dict):
    settings = {}
    data["defaultSettings"] = settings

configured = settings.get("customThemesPath")
target_dir = default_dir
if isinstance(configured, str) and configured.strip():
    configured = os.path.abspath(os.path.expanduser(configured))
    try:
        os.makedirs(configured, exist_ok=True)
        target_dir = configured
    except OSError as exc:
        print(f"hexciri heroic: cannot use customThemesPath {configured}: {exc}", file=sys.stderr)

target_file = os.path.join(target_dir, theme_id)
if os.path.abspath(target_file) != os.path.abspath(theme_file):
    try:
        with open(theme_file, "rb") as src, open(target_file, "wb") as dst:
            dst.write(src.read())
    except OSError as exc:
        print(f"hexciri heroic: cannot install {target_file}: {exc}", file=sys.stderr)
        sys.exit(3)

settings["customThemesPath"] = target_dir
# Legacy cleanup: older hexciri runs wrote `theme` into the main config; the
# renderer reads it from store/config.json instead, so keep main clean.
settings.pop("theme", None)
data["version"] = data.get("version") or "v0"

# The renderer configStore is a different file; this is the value its
# `ct.get("theme", ...)` reads at startup. Keep its mirrored settings object
# in sync when present.
store["theme"] = theme_id
if isinstance(store.get("settings"), dict):
    store["settings"]["customThemesPath"] = target_dir

try:
    write_json(config_path, data, 2)
    write_json(store_path, store, "\t")
except OSError as exc:
    print(f"hexciri heroic: could not write config ({exc})", file=sys.stderr)
    sys.exit(3)
PYEOF
    then
        warning "Heroic CSS updated, but its config could not be updated — select $theme_id manually"
    fi
else
    warning "python3 not found — set Heroic's Custom Themes Path to $heroic_themes and select $theme_id"
fi

require_restart "heroic" "Heroic"
success "Heroic theme updated!"
exit 0
