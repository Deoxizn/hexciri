#!/usr/bin/env bash
# 50-heroic.sh — render a Heroic Games Launcher custom theme and select it.
#
# Heroic 2.2x reads custom CSS from a directory set in
# Settings → Accessibility → Custom Themes Path. The CSS file name becomes the
# body class (hexciri.css → body.hexciri), and the file name itself is stored
# in the `theme` setting. There is no watcher: a running launcher must be
# restarted (or the theme unselected/reselected) after the file changes.
source "${HEXCIRI_THEME_ENV:-$HOME/.config/hexciri/hooks/lib/theme-env.sh}"

if ! command -v heroic >/dev/null 2>&1; then
    skipped "Heroic Launcher"
fi

heroic_dir="${XDG_CONFIG_HOME:-$HOME/.config}/heroic"
heroic_config="$heroic_dir/config.json"
heroic_themes="$heroic_dir/themes"
theme_id="hexciri.css"
theme_file="$heroic_themes/$theme_id"

# Derived surface shades. Heroic's built-in themes use several near-black
# layers; deriving them from the theme background keeps light themes coherent
# too (change_shade clamps per channel).
background="${primary_background}"
background_darker=$(change_shade "$background" -8)
background_deepest=$(change_shade "$background" -16)
background_secondary=$(change_shade "$background" 6)
background_lighter=$(change_shade "$background" 12)
background_hover=$(change_shade "$background" 9)

# Perceived luminance (ITU-R BT.601) for the two contrast decisions Heroic
# needs: secondary text must survive a light background, and button labels
# (--text-tertiary) sit on the accent/status colors, not on the background.
hex_luma() {
    local hex=${1#\#}
    [[ $hex =~ ^[0-9a-fA-F]{6}$ ]] || {
        printf '0\n'
        return
    }
    local r=$((16#${hex:0:2})) g=$((16#${hex:2:2})) b=$((16#${hex:4:2}))
    printf '%d\n' $(((r * 299 + g * 587 + b * 114) / 1000))
}

if (($(hex_luma "$background") >= 140)); then
    text_secondary=$(change_shade "$primary_foreground" 45)
    text_hover="$normal_blue"
else
    text_secondary="$bright_black"
    # Some palettes set color8 almost equal to color0; fall back to a shade of
    # the foreground when the muted slot would be invisible on the background.
    bg_luma=$(hex_luma "$background")
    secondary_luma=$(hex_luma "$text_secondary")
    if ((secondary_luma > bg_luma)); then
        secondary_gap=$((secondary_luma - bg_luma))
    else
        secondary_gap=$((bg_luma - secondary_luma))
    fi
    if ((secondary_gap < 30)); then
        text_secondary=$(change_shade "$primary_foreground" -45)
    fi
    text_hover="$bright_white"
fi

if (($(hex_luma "$normal_blue") >= 140)); then
    # Accent is light → the darker of background/foreground is the readable label.
    if (($(hex_luma "$background") <= $(hex_luma "$primary_foreground"))); then
        text_on_accent="$background"
    else
        text_on_accent="$primary_foreground"
    fi
else
    # Accent is dark → the lighter of background/foreground is the readable label.
    if (($(hex_luma "$background") >= $(hex_luma "$primary_foreground"))); then
        text_on_accent="$background"
    else
        text_on_accent="$primary_foreground"
    fi
fi

mkdir -p "$heroic_themes"

cat > "$theme_file" <<EOF
